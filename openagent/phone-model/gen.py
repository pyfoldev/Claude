def noisy(t):
    """Имитация распознавания речи: регистр, пунктуация, ё, опечатки, слова-паразиты."""
    r = R.random()
    if r < 0.4:
        t = t.lower()
    elif r < 0.55:
        t = t.capitalize() + pick(["", ".", "!", "?"])
    if R.random() < 0.3:
        t = t.replace("ё", "е")
    if R.random() < 0.12 and len(t) > 8:
        i = R.randint(1, len(t) - 2)
        k = R.random()
        t = t[:i] + t[i + 1:] if k < 0.5 else t[:i] + t[i + 1] + t[i] + t[i + 2:] if i + 2 < len(t) else t
    if R.random() < 0.05:
        t = t.replace(" ", "  ", 1)
    return t.strip()


def sample():
    gens, w = zip(*CATS)
    g = R.choices(gens, weights=w)[0]
    if g is g_neg:
        t, a = g()
        pre = ""
    else:
        r = R.random()
        if r < 0.10:   # две команды подряд
            g2 = R.choice(SINGLE_SIMPLE)
            t1, a1 = g()
            t2, a2 = g2()
            conj = pick([" и ", " и ", ", потом ", " а потом ", " затем ", ", ещё ", " и заодно ", " и сразу "])
            low = lambda s: s[0].lower() + s[1:]
            t, a = t1 + conj + low(t2), a1 + a2
        else:
            t, a = g()
        pre = pick(PRE)
    text = noisy(pre + t + (pick(POST) if g is not g_neg else ""))
    return text, a


