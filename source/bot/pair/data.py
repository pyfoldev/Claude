def level_name(level: int) -> str:
    if level <= len(LEVEL_NAMES):
        return LEVEL_NAMES[level - 1]
    name = LEVEL_NAMES[-1]
    for lvl, title in sorted(MILESTONES.items()):
        if level >= lvl:
            name = title
    return name


