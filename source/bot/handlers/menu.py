@router.message(CommandStart(deep_link=False), F.chat.type == "private")
async def onboarding(message: Message, bot, webapp_url: str = "") -> None:
    """/start в личке без параметров: короткое знакомство и три кнопки."""
    await rich_ui.send(bot, message.chat.id, onboarding_screen((await bot.me()).username, webapp_url))


@router.message(CommandStart())
@router.message(Command("menu", "help"))
@router.message(F.text.lower().in_({"меню", "команды", "помощь"}))
async def show_menu(message: Message, bot) -> None:
    await rich_ui.send(bot, message.chat.id, main_screen(),
                       thread_id=message.message_thread_id if message.is_topic_message else None)


@router.callback_query(F.data.startswith("menu:"))
async def menu_cb(cb: CallbackQuery, bot, db, webapp_url: str = "") -> None:
    key = cb.data.split(":", 1)[1]
    if key == "settings":
        from bot.handlers.settings import open_settings
        await open_settings(cb, bot, db, webapp_url)
        return
    await cb.answer()                                  # сначала снимаем «часики» с кнопки, потом правим сообщение
    if key == "home":
        await rich_ui.show(cb, main_screen())
    elif key in SECTION_DATA:
        await rich_ui.show(cb, section_screen(key, webapp_url if cb.message.chat.type == "private" else ""))
